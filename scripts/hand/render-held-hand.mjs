// Renders the two resting-hand images for the held close-up, and their framing:
//
//   pnpm hand:images        (after `pnpm hand:model`: it renders the shipped model)
//
// Headless Chromium (Playwright's) opens render/held-hand.html, which renders v10's final pose with three.js (a dev
// dependency, used only here) and returns two layers split at the card's plane, on transparent backgrounds:
//   src/scene/hand/held-hand-behind.webp   under the badge (the whole hand; the badge covers what's behind it)
//   src/scene/hand/held-hand-front.webp    over the badge (the hand's near side, and its soft shadow on the face)
//   src/scene/hand/held-hand.json          where they sit on the held badge (the framing contract: README.md)
// Both are lossless WebP at PX_PER_UNIT px per badge unit: 2× density for a held badge up to 1000 CSS px tall.
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import sharp from 'sharp';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const OUT_DIR = join(ROOT, 'src', 'scene', 'hand');

/** Image px per badge unit (1/500 of the held badge's height): 2 device px per CSS px at a 1000 px tall badge. */
const PX_PER_UNIT = 4;
/** How far down the images reach, in units from the badge's top edge: 100 below the badge, past any window's
    bottom edge in the held framing (about 12 units below the badge), as far as v10's own frame showed. */
const BOTTOM = 600;

const ORIGIN = 'http://hand.render';
const FILES = {
  '/render/': join(HERE, 'render'),
  '/three/': join(ROOT, 'node_modules', 'three'),
  '/hand.glb': join(ROOT, 'public', 'hand', 'hand.glb'),
};
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.glb': 'model/gltf-binary' };

/** Serves the page, three.js and the model from disk; nothing else is fetched. */
async function serveFiles(page) {
  await page.route(`${ORIGIN}/**`, (route) => {
    const path = new URL(route.request().url()).pathname;
    const prefix = Object.keys(FILES).find((p) => path === p || (p.endsWith('/') && path.startsWith(p)));
    if (!prefix) return route.fulfill({ status: 404 });
    const file = prefix.endsWith('/') ? join(FILES[prefix], path.slice(prefix.length)) : FILES[prefix];
    return route.fulfill({ body: readFileSync(file), contentType: TYPES[extname(file)] ?? 'application/octet-stream' });
  });
}

const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage();
  page.on('console', (m) => m.type() === 'error' && console.error('[page]', m.text()));
  page.on('pageerror', (e) => console.error('[page]', e));
  await serveFiles(page);
  await page.goto(`${ORIGIN}/render/held-hand.html`);
  await page.waitForFunction(() => window.__ready);
  const result = await page.evaluate(
    (o) => window.renderHeldHand(o),
    { modelUrl: '/hand.glb', pxPerUnit: PX_PER_UNIT, bottom: BOTTOM },
  );

  const unsolved = Object.entries(result.check.curls).filter(([, c]) => c === null);
  if (unsolved.length) throw new Error(`digits not resting on the face: ${unsolved.map(([d]) => d).join(', ')}`);

  // Lossless WebP at the encoder's highest effort (the browser's own WebP encoder is about twice the size).
  const png = (dataUrl) => Buffer.from(dataUrl.slice(dataUrl.indexOf(',') + 1), 'base64');
  for (const layer of ['behind', 'front'])
    await sharp(png(result[layer]))
      .webp({ lossless: true, effort: 6 })
      .toFile(join(OUT_DIR, `held-hand-${layer}.webp`));

  const framing = {
    $comment:
      'Generated by scripts/hand/render-held-hand.mjs (pnpm hand:images); see scripts/hand/README.md. Units: 1/500 of the held badge height; origin: the held badge top-left corner.',
    pxPerUnit: PX_PER_UNIT,
    box: result.box,
    reach: result.reach,
  };
  writeFileSync(join(OUT_DIR, 'held-hand.json'), `${JSON.stringify(framing, null, 2)}\n`);
  console.log('[images] box (units):', result.box, `→ ${result.box.width * PX_PER_UNIT}×${result.box.height * PX_PER_UNIT} px`);
  for (const layer of ['behind', 'front'])
    console.log(`[images] held-hand-${layer}.webp: ${statSync(join(OUT_DIR, `held-hand-${layer}.webp`)).size} B`);
  console.log('[images] reach over the face (units):', result.reach);
  console.log('[images] check:', result.check);
} finally {
  await browser.close();
}
